/**
 * Настройки компании из `companies.features` — docs/COMPANY_PIPELINE_PLAN.md §4.
 *
 * Чистый модуль: без базы, как lib/branding.ts. Его читает и очередь на сервере,
 * и форма в консоли.
 *
 * `features` — свободный JSONB, и это удобно ровно до того места, где от ключа
 * зависит, уедет ли чужая работа на наше железо. Опечатка в имени ключа при
 * записи читается как «флаг выключен», то есть тихо отменяет запрет — и увидеть
 * это можно только по факту, задним числом. Поэтому имя ключа объявлено ЗДЕСЬ
 * один раз, и отсюда же берёт его SQL очереди.
 */

/**
 * Имя ключа в JSONB. Экспортируется, потому что `visibilityClause` в
 * lib/pipeline/queue.ts подставляет его в запрос: два написания одного имени —
 * в форме и в очереди — рано или поздно разъедутся, и разъедутся молча.
 */
export const OWN_MACHINES_ONLY_KEY = "ownMachinesOnly"

/**
 * Слежение конвейера за компанией. Читается в `listWatchedProjects`
 * (lib/pipeline/repository.ts) — тоже подстановкой в SQL, см. выше.
 *
 * Умолчание у него ОБРАТНОЕ соседнему флагу: отсутствие ключа значит «включено».
 * Иначе выкатка этого кода погасила бы обработку всем компаниям сразу — у них
 * у всех ключа нет и взяться ему неоткуда.
 */
export const AUTOMATION_ENABLED_KEY = "automationEnabled"

export type CompanyFeatures = {
  /**
   * Обработка только на своих машинах.
   *
   * Отвечает на ОДИН вопрос: что делать, если своих машин у компании не осталось
   * совсем. Выключен — задачи берём на себя; включён — очередь стоит и ждёт,
   * пока машины заведут.
   *
   * На маршрут при живых машинах он не влияет никак: пока у компании есть хоть
   * одна незаотозванная строка машины, её задачи и так идут только туда (§3).
   */
  ownMachinesOnly: boolean
  /**
   * Конвейер следит за проектами компании — §5.
   *
   * Вторая ось к гейту на человеке (`users.automation_enabled`), а не замена
   * ему: этот выключает компанию целиком, тот — конкретного сотрудника. Работа
   * идёт, когда открыты ОБА; закрытый любой из них останавливает.
   *
   * Распоряжается им наша сторона, а не компания: это управление установкой.
   * Флаг «только свои машины» рядом — наоборот, их решение (§4, §6).
   */
  automationEnabled: boolean
}

/**
 * Кусок `WHERE` для «компания не выключена». Строка, а не запрос: базы этот
 * модуль не касается.
 *
 * Вынесен сюда, потому что читателей у гейта двое — слежение обработки
 * (lib/pipeline/repository.ts) и обход на постинг (lib/posting/repository.ts), —
 * и разойтись им нельзя: выключенная компания, которая перестала обрабатывать,
 * но продолжила постить, это ровно тот «выключенный проект, который всё равно
 * что-то делает», против которого написан докстринг постинга.
 *
 * Выключает только явный `false`, см. AUTOMATION_ENABLED_KEY. Сравнение с
 * jsonb, а не приведение к boolean: мусор под ключом не должен ронять запрос.
 *
 * @param userAlias псевдоним таблицы `users` в запросе — колонку `company_id`
 *   берём с него.
 */
export function companyAutomationSql(userAlias: string): string {
  return `NOT COALESCE(
            (SELECT c.features->'${AUTOMATION_ENABLED_KEY}' = 'false'::jsonb
               FROM companies c WHERE c.id = ${userAlias}.company_id),
            FALSE
          )`
}

export function readCompanyFeatures(raw: unknown): CompanyFeatures {
  const value = (raw ?? {}) as Record<string, unknown>
  return {
    // Строго `true`, а не «похоже на да»: строка "false" истинна в JS, и
    // мягкое чтение превратило бы её во включённый запрет.
    ownMachinesOnly: value[OWN_MACHINES_ONLY_KEY] === true,
    // И зеркально: выключает только явный `false`. Мусор под ключом оставляет
    // обработку идти — остановка должна быть чьим-то решением, а не следствием
    // кривого значения, которого никто не заметил.
    automationEnabled: value[AUTOMATION_ENABLED_KEY] !== false,
  }
}
