/**
 * Палитра текста элемента.
 *
 * ⚠️ Это ДАННЫЕ ФАЙЛА, а не оформление интерфейса. Формат разметки требует
 * `#RRGGBB` (markup.ts), потому что цвет уезжает в After Effects и там
 * подставляется в `setFillColor` — токена темы скрипт не поймёт, а к нашей
 * дизайн-системе композиция отношения не имеет. Поэтому коды цветов живут
 * здесь, в `lib/`, и ни один из них не попадает в классы или стили кабинета:
 * правило «только токены» осталось в силе для интерфейса.
 *
 * Набор — стартовый, а не закрытый: человек выбирает и произвольный цвет, а
 * ряд «уже использованные» в редакторе пополняется сам. Смысл списка в том,
 * чтобы первые титры не начинались с подбора оттенка вслепую.
 */

/** Стартовые цвета: контрастные между собой и различимые на любом фоне. */
export const ELEMENT_COLORS: readonly string[] = [
  "#FFFFFF",
  "#000000",
  "#FF3B30",
  "#FF9500",
  "#FFCC00",
  "#34C759",
  "#00C7BE",
  "#0A84FF",
  "#5E5CE6",
  "#BF5AF2",
]

/**
 * Множитель кегля задаётся шагами, а не выбором из списка.
 *
 * Размер — множитель, а не кегль: какой кегль окажется в композиции, заранее
 * неизвестно (план §8.2). Поэтому и нет «правильных» значений, из которых
 * можно составить список, — есть «чуть больше» и «чуть меньше», и шаг в
 * десятую даёт их обоих, не заставляя думать о числах.
 */
export const ELEMENT_SCALE_STEP = 0.1
export const ELEMENT_SCALE_MIN = 0.1
export const ELEMENT_SCALE_MAX = 10

/**
 * Шаг множителя.
 *
 * `null` — множитель вернулся к единице, и свойство надо СНЯТЬ, а не записать
 * как `x1`: единица ничего не меняет, а в файле выглядела бы как осознанное
 * решение автора. Так же и парсер: `x1` он прочтёт, но писать его незачем.
 *
 * Округление обязательно: `1.1 + 0.1` в двоичной арифметике даёт
 * `1.2000000000000002`, и это число уехало бы в файл как есть.
 */
export function stepScale(current: number, delta: number): number | null {
  const base = Number.isFinite(current) && current > 0 ? current : 1
  const rounded = Math.round((base + delta) * 10) / 10
  const clamped = Math.min(ELEMENT_SCALE_MAX, Math.max(ELEMENT_SCALE_MIN, rounded))
  return clamped === 1 ? null : clamped
}

/** Нормализация цвета к виду формата: `#rrggbb` → `#RRGGBB`. */
export function normalizeColor(raw: string): string | null {
  const value = raw.trim()
  if (!/^#[0-9a-f]{6}$/i.test(value)) return null
  return value.toUpperCase()
}
