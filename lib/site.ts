/**
 * Имя площадки.
 *
 * Зачем не литералом по месту: имя — то, чем упрощённая копия сайта отличается
 * на каждой второй странице. Оставь его в коде — и восемь общих файлов (шапка,
 * подвал, оба меню, письма, словарь) разойдутся с основной площадкой навсегда, а
 * каждое слияние будет спотыкаться именно о них. Та же причина, по которой
 * заведены выключатели: разница между площадками — настройка, а не правка кода
 * (docs/FEATURE_FLAGS.md §0).
 *
 * Префикс `NEXT_PUBLIC_` обязателен: имя стоит в клиентских компонентах, а туда
 * попадают только переменные с ним. Значение подставляется на сборке — у каждой
 * площадки своя сборка, что для отдельного развёртывания и так верно.
 */
export const SITE_NAME = process.env.NEXT_PUBLIC_SITE_NAME?.trim() || "FF Works"

/**
 * Монограмма для квадратного значка: первые буквы слов имени, не больше двух.
 *
 * Считается, а не задаётся своей переменной: это было бы второе место, где имя
 * можно забыть поменять, и значок ещё год показывал бы чужие буквы.
 */
export const SITE_MONOGRAM =
  SITE_NAME.split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((word) => word[0])
    .join("")
    .toUpperCase() || "FF"
