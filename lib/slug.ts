/**
 * Латинский идентификатор из человеческого названия.
 *
 * Чистый модуль в `lib/`, а не при компоненте: таблица транслитерации — это
 * данные, а не текст интерфейса, и в локализуемой зоне (`components/admin`)
 * её кириллицу справедливо ловил бы `npm run i18n:check`.
 *
 * Транслитерация обязательна, а не украшение: без неё подсказка slug пуста у
 * любого русского названия — то есть у всех, — и кнопка «Создать» гаснет на
 * первом же заведении компании, не объясняя почему.
 */
const TRANSLIT: Record<string, string> = {
  "а": "a", "б": "b", "в": "v", "г": "g", "д": "d",
  "е": "e", "ё": "e", "ж": "zh", "з": "z", "и": "i",
  "й": "i", "к": "k", "л": "l", "м": "m", "н": "n",
  "о": "o", "п": "p", "р": "r", "с": "s", "т": "t",
  "у": "u", "ф": "f", "х": "h", "ц": "c", "ч": "ch",
  "ш": "sh", "щ": "sch", "ъ": "", "ы": "y", "ь": "",
  "э": "e", "ю": "yu", "я": "ya",
}

/** Правило то же, что у `companyCreateSchema.slug`: `^[a-z0-9]+(-[a-z0-9]+)*$`. */
export function slugify(value: string): string {
  return value
    .toLowerCase()
    .trim()
    .replace(/[а-яё]/g, (letter) => TRANSLIT[letter] ?? letter)
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}
