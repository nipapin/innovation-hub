-- Отметка «команда прочитала чат проекта».
--
-- Зеркало к projects.chat_last_read_at, который принадлежит владельцу проекта.
-- Отметка одна на проект, а не на каждого админа: со стороны сайта чат ведёт
-- команда, и прочитанное одним прочитано всеми — ровно так же, как в YouGile,
-- где та же переписка лежит в общем чате.
--
-- Заполнять её при накатке не нужно. NULL здесь означает «на сайте чат не
-- открывали», и счётчик в этом случае ведёт себя как раньше: непрочитанным
-- считается то, что пришло от клиента после ПОСЛЕДНЕГО ответа команды
-- (lib/repositories/project-chat.ts, TEAM_READ_MARK_SQL). Ответ, написанный в
-- YouGile, продолжает гасить счётчик сам — иначе на сайте копился бы вечный
-- долг из переписки, которую давно закрыли на той стороне.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS chat_team_last_read_at TIMESTAMPTZ;

