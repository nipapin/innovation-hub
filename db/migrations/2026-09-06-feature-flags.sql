-- Выключатели частей сайта. Контракт целиком — docs/FEATURE_FLAGS.md.
--
-- Зачем таблица, а не домен в automation_settings: там общие словари
-- (`{name, path[], color, isDefault}`), и они синхронизируются на десктоп и на
-- машины конвейера. Флаг — это `ключ → да/нет`, форма другая, а машинам знать о
-- том, какие разделы сайта показаны в браузере, незачем вовсе.
--
-- Строка здесь означает РЕШЕНИЕ ЧЕЛОВЕКА, а не состояние флага. Флаг, которого
-- никто не трогал, строки не имеет: его значение берётся из умолчания установки
-- (FEATURE_DEFAULT). Поэтому новый флаг в коде не требует ни миграции, ни сида, и
-- на копии сайта приезжает выключенным сам, без ручной работы.
--
-- Ключ не ссылается на реестр внешним ключом и не проверяется CHECK-ом: реестр
-- живёт в коде (lib/features.ts), и строка от удалённого флага должна пережить
-- откат релиза. Неизвестные ключи отсеиваются при чтении.

CREATE TABLE IF NOT EXISTS feature_flags (
  key        TEXT PRIMARY KEY,
  enabled    BOOLEAN NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Кто переключил. Первый вопрос, который задают, увидев погасший раздел.
  updated_by TEXT REFERENCES users(id) ON DELETE SET NULL
);
