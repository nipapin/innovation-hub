-- Аккаунты площадок: сейф для того, чем сайт будет публиковать.
-- Разбор и обоснования — docs/SOCIAL_POSTING_PLAN.md §4.
--
-- Миграция ничего не включает: таблицы появляются пустыми, постинга ещё нет,
-- поведение сайта не меняется. До первого подключённого аккаунта ничего не
-- происходит.
--
-- ⚠️ Шифрование требует `VAULT_MASTER_KEY` в окружении — тот же мастер-ключ, что
-- у ключей вендоров (lib/vault/crypto.ts). Без него аккаунт нельзя подключить:
-- сайт откажется писать секрет, который не сможет прочитать.
--
-- ── Почему отдельные таблицы, а не vendor_accounts ──────────────────────────
--
-- План (§4) прямо описывает свою таблицу аккаунтов площадок, и вот почему это
-- не то же самое, что учётка вендора:
--
--   • у ключа вендора есть ПРАЙС и РАСХОД — на них держится себестоимость
--     обработки. У аккаунта VK ни того, ни другого нет и не будет;
--   • у аккаунта площадки есть СРОК ЖИЗНИ токена и КАТАЛОГ ЦЕЛЕЙ (группы,
--     каналы), которых у ключа вендора нет;
--   • ключ вендора уезжает НА МАШИНУ со сроком (delivery `keys`), токен
--     площадки не покидает сервер никогда — публикует сам сайт.
--
-- Общее у них — крипто и процедура отзыва, и они действительно общие:
-- шифрует обе таблицы `lib/vault/crypto.ts`, отзыв в обеих означает одно и то
-- же (строка секрета получает `revoked_at`, живых версий не остаётся). Именно
-- этого требовал §4 — не одной таблицы, а одного сейфа.

-- ── Аккаунты ────────────────────────────────────────────────────────────────
--
-- Аккаунт принадлежит ЧЕЛОВЕКУ, а не проекту и не клиенту. В программе они
-- лежат по главным папкам (accounts/<mainFolder>/<platform>.json), потому что
-- там главная папка и есть человек. На сайте человек уже есть — и один
-- подключённый VK работает во всех его проектах сразу. Иначе подключать его
-- пришлось бы в каждом проекте заново, и отзывать — тоже в каждом.
CREATE TABLE IF NOT EXISTS social_accounts (
  id            TEXT PRIMARY KEY,
  user_id       TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  platform      TEXT NOT NULL CHECK (platform IN ('vk', 'youtube', 'telegram')),

  -- Человекочитаемое имя: «Иван Петров», «канал студии». Именно оно уезжает в
  -- `options.json` проекта — не секрет и не id, ровно как метка учётки вендора.
  -- Поэтому же оно уникально в паре «человек + площадка»: два одинаковых имени
  -- сделали бы ссылку из графа двусмысленной.
  --
  -- Совместимость с программой держится на этом поле: в графе, нарисованном в
  -- программе, у ноды Poster в `account` лежит ИМЯ аккаунта, и сайт обязан
  -- искать по нему же.
  label         TEXT NOT NULL,

  -- id на самой площадке: user_id у VK, id канала у YouTube, id бота у
  -- Telegram. Нужен, чтобы отличить переподключённый тот же аккаунт от
  -- другого: имя человек может поменять на площадке, id — нет.
  external_id   TEXT NOT NULL DEFAULT '',

  -- Каталог целей публикации: группы VK, каналы Telegram, плейлисты YouTube.
  -- Кэш, а не источник истины — истина у площадки, и обновляется он кнопкой и
  -- перед постановкой задачи. Кэш нужен, чтобы выпадающий список открывался
  -- мгновенно и не ходил в VK на каждый показ формы.
  meta          JSONB NOT NULL DEFAULT '{}'::jsonb,

  status        TEXT NOT NULL DEFAULT 'active'
                  CHECK (status IN ('active', 'revoked')),

  -- Когда токен последний раз ответил площадке, и чем ответил при отказе.
  -- «Токен протух» обязано быть видно на экране аккаунтов, а не выясняться из
  -- упавшей публикации через сутки.
  checked_at    TIMESTAMPTZ,
  last_error    TEXT,

  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  UNIQUE (user_id, platform, label)
);

CREATE INDEX IF NOT EXISTS social_accounts_owner_idx
  ON social_accounts (user_id, platform);

-- ── Секреты аккаунтов ───────────────────────────────────────────────────────
--
-- Версия, а не поле — та же причина, что у секретов вендора: переподключение
-- добавляет строку, старая живёт до отзыва, иначе публикация в полёте упала бы
-- в момент замены токена.
--
-- В `ciphertext` лежит JSON-ОБЪЕКТ, зашифрованный целиком: у VK это
-- `{ accessToken }`, у YouTube — `{ clientId, clientSecret, refreshToken }`, у
-- Telegram — `{ botToken }`. Хранить их одной строкой значило бы разбирать её
-- разделителем, а разделитель однажды встретится внутри секрета.
CREATE TABLE IF NOT EXISTS social_account_secrets (
  id          TEXT PRIMARY KEY,
  account_id  TEXT NOT NULL REFERENCES social_accounts(id) ON DELETE CASCADE,
  version     INTEGER NOT NULL CHECK (version > 0),
  ciphertext  TEXT NOT NULL,
  -- «••••4f21»: узнать глазами, какой токен лежит, не доставая его.
  hint        TEXT NOT NULL DEFAULT '',
  -- Когда токен перестанет работать. NULL — бессрочный: у VK со scope `offline`
  -- он именно такой, и выдумывать ему срок нельзя — иначе рабочий аккаунт
  -- однажды сам себя погасит.
  expires_at  TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  revoked_at  TIMESTAMPTZ,
  UNIQUE (account_id, version)
);

-- Живая версия — старшая непогашенная. Частичный индекс ровно под этот вопрос:
-- его задаёт каждая публикация.
CREATE INDEX IF NOT EXISTS social_account_secrets_live_idx
  ON social_account_secrets (account_id, version DESC) WHERE revoked_at IS NULL;
