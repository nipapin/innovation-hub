-- Сброс пароля по ссылке из письма.
--
-- Появилась, потому что до неё забытый пароль было нечем восстановить: аккаунты
-- заводятся приглашением (lib/invite-account.ts), временный пароль уходит
-- письмом и НИГДЕ не хранится — в базе только хэш. Не дошедшее письмо означало
-- запертый навсегда аккаунт, и починить его мог лишь администратор руками.
--
-- Хранится ХЭШ токена, а не сам токен, — как в machine_tokens. Дамп базы и так
-- содержит достаточно, чтобы не добавлять к нему готовые ключи входа: утёкший
-- столбец с сырыми токенами позволил бы сменить пароль любому, у кого запрос
-- ещё не истёк. Сырой токен живёт только в ссылке внутри письма.
CREATE TABLE IF NOT EXISTS password_resets (
  id          TEXT PRIMARY KEY,
  user_id     TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash  TEXT NOT NULL UNIQUE,
  expires_at  TIMESTAMPTZ NOT NULL,
  -- Отметка о применении, а не удаление строки: повторный переход по той же
  -- ссылке обязан отличаться от перехода по выдуманной. Удалённая строка дала
  -- бы «ссылка недействительна» в обоих случаях, и человек, нажавший на письмо
  -- дважды, решил бы, что сброс не сработал, и запросил бы ещё один.
  used_at     TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Запрос приходит с токеном, поэтому основной поиск идёт по token_hash (его
-- покрывает UNIQUE). Индекс по пользователю нужен другому читателю: выдача
-- нового запроса гасит прежние, чтобы у человека не осталось на руках
-- нескольких живых ссылок.
CREATE INDEX IF NOT EXISTS password_resets_user_idx
  ON password_resets (user_id)
  WHERE used_at IS NULL;
