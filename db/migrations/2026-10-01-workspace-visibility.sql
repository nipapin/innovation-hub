-- Что показывать в меню кабинета — настройки самого человека.
--
-- `personal_hidden` — на ВХОДЕ: раздел «Личное» не показывается в переключателе
-- профилей, и вход открывает компанию. Это не выключение: «Личное» остаётся
-- входом со всеми данными, и его можно вернуть из настроек любого профиля.
-- Если активных компаний не осталось, «Личное» показывается всё равно —
-- иначе человеку было бы некуда войти.
--
-- `hidden_nav` — на ПРОФИЛЕ (вход или подпрофиль): ключи пунктов рабочего места,
-- убранных из бокового меню. У каждого рабочего места свой набор. Доступ к
-- разделам не меняется, прячется только пункт.
--
-- Код переживает отсутствие обеих колонок (lib/repositories/users.ts,
-- readWorkspacePrefs), поэтому миграция может идти и раньше, и позже кода.
-- Существующие аккаунты не трогаем: скрыть «Личное» каждый решает сам.
ALTER TABLE users
  ADD COLUMN IF NOT EXISTS personal_hidden BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS hidden_nav TEXT[] NOT NULL DEFAULT '{}';
